-- =====================================================================
-- Flight Booking System - core schema
-- Portable between PostgreSQL 13+ and H2 (MODE=PostgreSQL) used in tests.
-- =====================================================================

CREATE TABLE users (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name      VARCHAR(100) NOT NULL,
    email          VARCHAR(150) NOT NULL,
    password_hash  VARCHAR(100) NOT NULL,
    phone          VARCHAR(15),
    role           VARCHAR(10)  NOT NULL,
    created_at     TIMESTAMP    NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('USER', 'ADMIN'))
);

CREATE TABLE airports (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code     VARCHAR(3)   NOT NULL,
    name     VARCHAR(120) NOT NULL,
    city     VARCHAR(80)  NOT NULL,
    country  VARCHAR(80)  NOT NULL,
    CONSTRAINT uk_airports_code UNIQUE (code)
);

CREATE TABLE airlines (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code  VARCHAR(3)   NOT NULL,
    name  VARCHAR(100) NOT NULL,
    CONSTRAINT uk_airlines_code UNIQUE (code)
);

CREATE TABLE flights (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_number           VARCHAR(10) NOT NULL,
    airline_id              BIGINT      NOT NULL,
    source_airport_id       BIGINT      NOT NULL,
    destination_airport_id  BIGINT      NOT NULL,
    aircraft_model          VARCHAR(50) NOT NULL,
    business_seats          INT         NOT NULL,
    economy_seats           INT         NOT NULL,
    CONSTRAINT uk_flights_number UNIQUE (flight_number),
    CONSTRAINT fk_flights_airline FOREIGN KEY (airline_id) REFERENCES airlines (id),
    CONSTRAINT fk_flights_source FOREIGN KEY (source_airport_id) REFERENCES airports (id),
    CONSTRAINT fk_flights_destination FOREIGN KEY (destination_airport_id) REFERENCES airports (id),
    CONSTRAINT ck_flights_route CHECK (source_airport_id <> destination_airport_id),
    CONSTRAINT ck_flights_seats CHECK (business_seats >= 0 AND economy_seats > 0)
);
CREATE INDEX idx_flights_route ON flights (source_airport_id, destination_airport_id);
CREATE INDEX idx_flights_airline ON flights (airline_id);

CREATE TABLE flight_schedules (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_id           BIGINT        NOT NULL,
    departure_time      TIMESTAMP     NOT NULL,
    arrival_time        TIMESTAMP     NOT NULL,
    economy_base_fare   NUMERIC(10,2) NOT NULL,
    business_base_fare  NUMERIC(10,2) NOT NULL,
    status              VARCHAR(15)   NOT NULL,
    CONSTRAINT fk_schedules_flight FOREIGN KEY (flight_id) REFERENCES flights (id),
    CONSTRAINT uk_schedules_flight_departure UNIQUE (flight_id, departure_time),
    CONSTRAINT ck_schedules_times CHECK (arrival_time > departure_time),
    CONSTRAINT ck_schedules_fares CHECK (economy_base_fare > 0 AND business_base_fare > 0),
    CONSTRAINT ck_schedules_status CHECK (status IN ('SCHEDULED', 'CANCELLED'))
);
-- Search filters schedules by departure window after resolving the route's flights.
CREATE INDEX idx_schedules_departure ON flight_schedules (departure_time, status);
CREATE INDEX idx_schedules_flight_departure ON flight_schedules (flight_id, departure_time);

CREATE TABLE bookings (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pnr              VARCHAR(8)    NOT NULL,
    user_id          BIGINT        NOT NULL,
    schedule_id      BIGINT        NOT NULL,
    seat_class       VARCHAR(10)   NOT NULL,
    status           VARCHAR(20)   NOT NULL,
    total_amount     NUMERIC(12,2) NOT NULL,
    coupon_code      VARCHAR(20),
    hold_expires_at  TIMESTAMP,
    failure_reason   VARCHAR(255),
    created_at       TIMESTAMP     NOT NULL,
    updated_at       TIMESTAMP     NOT NULL,
    CONSTRAINT uk_bookings_pnr UNIQUE (pnr),
    CONSTRAINT fk_bookings_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_bookings_schedule FOREIGN KEY (schedule_id) REFERENCES flight_schedules (id),
    CONSTRAINT ck_bookings_amount CHECK (total_amount >= 0),
    CONSTRAINT ck_bookings_seat_class CHECK (seat_class IN ('ECONOMY', 'BUSINESS')),
    CONSTRAINT ck_bookings_status CHECK (status IN ('INITIATED', 'SEATS_HELD', 'PAYMENT_PENDING',
                                                    'CONFIRMED', 'FAILED', 'CANCELLED', 'REFUNDED'))
);
CREATE INDEX idx_bookings_user_created ON bookings (user_id, created_at);
CREATE INDEX idx_bookings_schedule ON bookings (schedule_id);
-- Used by the hold-expiry job: WHERE status = 'SEATS_HELD' AND hold_expires_at < now
CREATE INDEX idx_bookings_status_hold ON bookings (status, hold_expires_at);

CREATE TABLE seats (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id      BIGINT      NOT NULL,
    seat_number      VARCHAR(5)  NOT NULL,
    seat_class       VARCHAR(10) NOT NULL,
    status           VARCHAR(10) NOT NULL,
    booking_id       BIGINT,
    hold_expires_at  TIMESTAMP,
    version          BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT fk_seats_schedule FOREIGN KEY (schedule_id) REFERENCES flight_schedules (id) ON DELETE CASCADE,
    CONSTRAINT fk_seats_booking FOREIGN KEY (booking_id) REFERENCES bookings (id),
    CONSTRAINT uk_seats_schedule_number UNIQUE (schedule_id, seat_number),
    CONSTRAINT ck_seats_class CHECK (seat_class IN ('ECONOMY', 'BUSINESS')),
    CONSTRAINT ck_seats_status CHECK (status IN ('AVAILABLE', 'HELD', 'BOOKED')),
    -- Invariant: a seat has an owning booking iff it is not AVAILABLE; only HELD seats carry an expiry.
    CONSTRAINT ck_seats_owner CHECK (
        (status = 'AVAILABLE' AND booking_id IS NULL AND hold_expires_at IS NULL)
        OR (status = 'HELD' AND booking_id IS NOT NULL AND hold_expires_at IS NOT NULL)
        OR (status = 'BOOKED' AND booking_id IS NOT NULL AND hold_expires_at IS NULL))
);
-- Availability counts in search: GROUP BY schedule_id, seat_class WHERE status = 'AVAILABLE'
CREATE INDEX idx_seats_schedule_status ON seats (schedule_id, status, seat_class);
CREATE INDEX idx_seats_booking ON seats (booking_id);

CREATE TABLE passengers (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id  BIGINT        NOT NULL,
    full_name   VARCHAR(100)  NOT NULL,
    age         INT           NOT NULL,
    gender      VARCHAR(10)   NOT NULL,
    seat_id     BIGINT        NOT NULL,
    fare        NUMERIC(10,2) NOT NULL,
    CONSTRAINT fk_passengers_booking FOREIGN KEY (booking_id) REFERENCES bookings (id) ON DELETE CASCADE,
    CONSTRAINT fk_passengers_seat FOREIGN KEY (seat_id) REFERENCES seats (id),
    CONSTRAINT uk_passengers_booking_seat UNIQUE (booking_id, seat_id),
    CONSTRAINT ck_passengers_age CHECK (age BETWEEN 0 AND 120),
    CONSTRAINT ck_passengers_gender CHECK (gender IN ('MALE', 'FEMALE', 'OTHER'))
);
CREATE INDEX idx_passengers_seat ON passengers (seat_id);

CREATE TABLE payments (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id         BIGINT        NOT NULL,
    method             VARCHAR(10)   NOT NULL,
    status             VARCHAR(10)   NOT NULL,
    amount             NUMERIC(12,2) NOT NULL,
    gateway_reference  VARCHAR(64),
    failure_reason     VARCHAR(255),
    created_at         TIMESTAMP     NOT NULL,
    updated_at         TIMESTAMP     NOT NULL,
    CONSTRAINT fk_payments_booking FOREIGN KEY (booking_id) REFERENCES bookings (id),
    CONSTRAINT uk_payments_gateway_ref UNIQUE (gateway_reference),
    CONSTRAINT ck_payments_method CHECK (method IN ('UPI', 'CARD')),
    CONSTRAINT ck_payments_status CHECK (status IN ('INITIATED', 'SUCCESS', 'FAILED', 'REFUNDED')),
    CONSTRAINT ck_payments_amount CHECK (amount >= 0)
);
CREATE INDEX idx_payments_booking ON payments (booking_id, status);

CREATE TABLE idempotency_keys (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key  VARCHAR(100)   NOT NULL,
    user_id          BIGINT         NOT NULL,
    operation        VARCHAR(40)    NOT NULL,
    request_hash     VARCHAR(64)    NOT NULL,
    status           VARCHAR(15)    NOT NULL,
    response_status  INT,
    response_body    VARCHAR(10000),
    created_at       TIMESTAMP      NOT NULL,
    CONSTRAINT fk_idempotency_user FOREIGN KEY (user_id) REFERENCES users (id),
    -- The unique key is what makes concurrent duplicate requests safe: only one INSERT can win.
    CONSTRAINT uk_idempotency_scope UNIQUE (idempotency_key, user_id, operation),
    CONSTRAINT ck_idempotency_status CHECK (status IN ('IN_PROGRESS', 'COMPLETED'))
);
CREATE INDEX idx_idempotency_created ON idempotency_keys (created_at);
